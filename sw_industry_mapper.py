def map_sw2_to_sw1(code):
    """
    单个申万二级行业代码 -> 统一一级行业代码。

    无法可靠映射时返回 None。
    """

    if code is None:
        return None

    try:
        code = int(code)
    except Exception:
        return None

    if code <= 0:
        return None

    if code == INVALID_CODE:
        return None

    # 特殊历史映射
    if code in SPECIAL_MAP:
        return SPECIAL_MAP[code]

    # 旧采掘剩余分类先不硬映射
    if code in (210300, 210400):
        return None

    # 普通二级 -> 一级
    level1 = (
        code // 10000
    ) * 10000

    if level1 in SUPPORTED_LEVEL1:
        return level1

    return None